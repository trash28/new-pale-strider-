import { BossLegMountSpec, BossVariantId, BossVariantSpec } from './bossTypes';

/**
 * Generates 10–16 articulated heavy spider-crawler legs spaced along the boss chassis
 * with 4-phase wave gait groups so at least ~70-75% of feet remain planted at all times.
 */
function buildBossLegs(
  pairs: number,
  hullHalfLen: number,
  hullHalfWidth: number,
  reach: number,
  femurLen: number,
  tibiaLen: number
): BossLegMountSpec[] {
  const legs: BossLegMountSpec[] = [];
  let id = 0;
  for (let i = 0; i < pairs; i++) {
    const t = pairs === 1 ? 0 : (i / (pairs - 1)) * 2 - 1; // +1 front .. -1 rear
    const ax = -t * hullHalfLen * 0.86;
    const widthCurve = 1 - Math.abs(t) * 0.16;
    const ay = hullHalfWidth * widthCurve;
    const rx = ax * 1.18;
    const ry = ay + reach;
    const gaitLeft = (i % 4) as 0 | 1 | 2 | 3;
    const gaitRight = ((i + 2) % 4) as 0 | 1 | 2 | 3;

    legs.push({
      id: id++,
      side: 'left',
      attachX: ax,
      attachY: -ay,
      restX: rx,
      restY: -ry,
      femurLength: femurLen,
      tibiaLength: tibiaLen,
      gaitGroup: gaitLeft,
      bendSign: -1,
    });
    legs.push({
      id: id++,
      side: 'right',
      attachX: ax,
      attachY: ay,
      restX: rx,
      restY: ry,
      femurLength: femurLen,
      tibiaLength: tibiaLen,
      gaitGroup: gaitRight,
      bendSign: 1,
    });
  }
  return legs;
}

