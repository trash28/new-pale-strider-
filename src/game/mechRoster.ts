function makeSymmetricLegs(
  pairs: { attachX: number; attachY: number; restX: number; restY: number; femur: number; tibia: number }[]
): LegMountSpec[] {
  const legs: LegMountSpec[] = [];
  pairs.forEach((p, idx) => {
    const groupA = (idx % 2) as 0 | 1;
    const groupB = ((idx + 1) % 2) as 0 | 1;
    // Left side (-Y in mech local frame where +X is forward)
    legs.push({
      side: 'left',
      attachX: p.attachX,
      attachY: -p.attachY,
      restX: p.restX,
      restY: -p.restY,
      femurLength: p.femur,
      tibiaLength: p.tibia,
      gaitGroup: groupA,
      bendSign: -1,
    });
    // Right side (+Y in mech local frame)
    legs.push({
      side: 'right',
      attachX: p.attachX,
      attachY: p.attachY,
      restX: p.restX,
      restY: p.restY,
      femurLength: p.femur,
      tibiaLength: p.tibia,
      gaitGroup: groupB,
      bendSign: 1,
    });
  });
  return legs;
}

