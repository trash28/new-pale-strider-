export interface ComputedMechStats {
  mass: number;
  acceleration: number;
  maxSpeed: number;
  turnSpeed: number;
  turnAccel: number;
  lateralGrip: number;
  armor: number;
  chassis: number;
  legDurability: number;
  sensorRange: number;
  reloadMult: number;
  fireRateMult: number;
  recoilMult: number;
  spreadMult: number;
  terrainPenaltyMult: number;
  damageMult: number;
}

export function computeEffectiveMechStats(
  spec: MechClassSpec,
  custom?: MechLoadoutCustomization
): ComputedMechStats {
  const up = custom?.upgrades ?? {};
  const eng = up.engine_output ?? 0;
  const turn = up.turn_servos ?? 0;
  const arm = up.composite_armor ?? 0;
  const rec = up.recoil_dampeners ?? 0;
  const ldr = up.auto_loader ?? 0;
  const opt = up.optics_suite ?? 0;
  const leg = up.leg_actuators ?? 0;
  const sus = up.suspension_kit ?? 0;

  const aaMassPenalty =
    (up.aa_targeting ?? 0) * 0.03 +
    (up.aa_servos ?? 0) * 0.02 +
    (up.aa_ammo ?? 0) * 0.03 +
    (up.aa_cooling ?? 0) * 0.03 +
    (up.aa_reinforced ?? 0) * 0.04;

  let massMult = 1 + eng * 0.04 + arm * 0.08 + rec * 0.03 + leg * 0.04 + aaMassPenalty;
  let accelMult = 1 + eng * 0.1 - arm * 0.06;
  let maxSpeedMult = 1 + eng * 0.07 - turn * 0.025;
  let armorMult = 1 + arm * 0.18;
  let damageMult = 1;
  let fireRateMult = 1 + ldr * 0.08;
  let reloadMult = 1 + ldr * 0.12;
  let recoilMult = Math.max(0.4, 1 - rec * 0.18);
  let spreadMult = Math.max(0.45, 1 - rec * 0.14 + ldr * 0.06);

  if (custom?.armorPackage === 'reactive') {
    armorMult += 0.15;
    massMult += 0.08;
    accelMult -= 0.08;
  } else if (custom?.armorPackage === 'lightweight') {
    armorMult -= 0.15;
    massMult -= 0.1;
    accelMult += 0.12;
    maxSpeedMult += 0.08;
  }

  if (custom?.weaponVariant === 'heavy_barrel') {
    damageMult += 0.15;
    recoilMult += 0.18;
    fireRateMult -= 0.08;
  } else if (custom?.weaponVariant === 'rapid_feed') {
    fireRateMult += 0.16;
    damageMult -= 0.08;
    spreadMult += 0.14;
  }

  return {
    mass: spec.mass * massMult,
    acceleration: spec.acceleration * Math.max(0.65, accelMult),
    maxSpeed: spec.maxSpeed * Math.max(0.7, maxSpeedMult),
    turnSpeed: spec.maxTurnSpeed * (1 + turn * 0.14),
    turnAccel: spec.turnAccel * (1 + turn * 0.14),
    lateralGrip: spec.lateralGrip * (1 + sus * 0.08 - eng * 0.03),
    armor: Math.round(spec.baseArmor * armorMult),
    chassis: spec.baseChassis,
    legDurability: Math.round(spec.legDurability * (1 + leg * 0.22)),
    sensorRange: Math.round(spec.sensorRange * (1 + opt * 0.16)),
    reloadMult,
    fireRateMult,
    recoilMult,
    spreadMult,
    terrainPenaltyMult: Math.max(0.45, 1 - sus * 0.15),
    damageMult,
  };
}
